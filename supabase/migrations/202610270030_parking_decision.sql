-- Stack C, C4: parking decisions (docs/designs/2026-10-26-parking-conditions-and-fees.md §3.2).
--
-- 1. City rules can end: city_rules gets expires_on and is renamed
--    city_rules_data. A rule is expired from expires_on on, in Taiwan
--    ((now() at time zone 'Asia/Taipei')::date >= expires_on); the app then
--    reads 「此地區的規則已過期」 and never falls back to the national rule.
-- 2. Builds before C4 read `city_rules` and do not know expires_on. Hiding
--    expired rows is not enough: those builds load the bundled rules first
--    and only replace them with the rows they get back, so a missing row
--    would bring back the bundled opening. `city_rules` is now a view that
--    returns every row, with expired ones projected so those builds read
--    them as unverified: nothing allowed, everything that was open or
--    conditional conditional, no district-only kinds, restriction
--    'unverified', the expiry as the exception text, version unchanged so
--    it still replaces the bundled copy.
-- 3. city_rules_v2(): the stored rows, expired ones and expires_on
--    included, for C4 builds and the admin site. Clients hold no grant on
--    city_rules_data.
-- 4. rule_verdict(): step 2 of the decision as a pure function, the SQL
--    side of ruleVerdict() in lib/domain/parking_decision.dart and
--    supabase/functions/_shared/rule_verdict.ts; all three run
--    supabase/functions/_shared/rule_verdict_cases.json
--    (supabase/tests/rule_verdict_test.sql, generated by
--    tool/gen_contract_sql.py).
-- 5. admin_upsert_city_rule() writes city_rules_data and takes expires_on.
--
-- The data_versions trigger (#108) and the restriction check move with the
-- table. An expiry is not a write, so it bumps no version: an old build
-- keeps a copy fetched before the end date until it next reloads the rules.

alter table public.city_rules rename to city_rules_data;
alter table public.city_rules_data add column expires_on date;
alter table public.city_rules_data add constraint city_rules_expires_after_effective
  check (expires_on is null or expires_on > effective_date);
revoke all on public.city_rules_data from anon,authenticated;

create function public.city_rules_v2() returns setof public.city_rules_data
language sql stable security definer set search_path='' as $$
  select * from public.city_rules_data order by city,vehicle;
$$;
revoke all on function public.city_rules_v2() from public;
grant execute on function public.city_rules_v2() to anon,authenticated;

-- Reads through city_rules_v2(), so it can stay security_invoker while
-- clients have no grant on the table.
create view public.city_rules with (security_invoker=on) as
select r.city,r.vehicle,
  case when x.expired then '[]'::jsonb else r.allowed_space_types end as allowed_space_types,
  case when x.expired then (
      select coalesce(jsonb_agg(t order by t),'[]'::jsonb) from (
        select jsonb_array_elements_text(r.allowed_space_types) t
        union select jsonb_array_elements_text(r.conditional_space_types)
        union select jsonb_object_keys(r.district_space_types)) u)
    else r.conditional_space_types end as conditional_space_types,
  r.districts,r.fee_note,
  case when x.expired then '此地區的規則已過期，請以現場標誌標線為準' else r.exceptions end as exceptions,
  r.can_use_two_spaces,r.effective_date,r.source_url,r.version,
  case when x.expired then 'unverified' else r.restriction end as restriction,
  case when x.expired then '{}'::jsonb else r.district_space_types end as district_space_types,
  r.expires_on
from public.city_rules_v2() r
cross join lateral (select r.expires_on is not null
  and r.expires_on<=(now() at time zone 'Asia/Taipei')::date as expired) x;
revoke all on public.city_rules from anon,authenticated;
grant select on public.city_rules to anon,authenticated;

-- One rule's verdict on a street bay kind (§3.2 step 2); see rule_verdict().
create function public.rule_verdict_one(p_rule jsonb,p_kind text,p_district text) returns jsonb
language plpgsql immutable set search_path='' as $$
declare
  v_open jsonb:=p_rule->'district_space_types'->p_kind;
  v_limited boolean:=coalesce(p_rule->'conditional_space_types','[]'::jsonb) ? p_kind;
  v_restriction text:=p_rule->>'restriction';
  v_districts jsonb:=coalesce(p_rule->'districts','[]'::jsonb);
begin
  if v_open is not null and jsonb_typeof(v_open)='array' then
    if p_district='' then return '{"verdict":"unknownDistrict","restriction":null}'; end if;
    if not v_open ? p_district then return '{"verdict":"closed","restriction":null}'; end if;
  else
    v_open:=null;
  end if;
  if v_limited and v_restriction='unverified' then
    return '{"verdict":"conditional","restriction":"unverified"}';
  end if;
  if not v_limited and v_open is null
     and not coalesce(p_rule->'allowed_space_types','[]'::jsonb) ? p_kind then
    return '{"verdict":"closed","restriction":null}';
  end if;
  if jsonb_array_length(v_districts)>0 and not v_districts ? p_district then
    return '{"verdict":"unknownDistrict","restriction":null}';
  end if;
  if v_limited then
    return jsonb_build_object('verdict','conditional','restriction',
      case when v_restriction in ('signage','unverified','time_limited','ev_only') then v_restriction end);
  end if;
  return '{"verdict":"open","restriction":null}';
end $$;
revoke all on function public.rule_verdict_one(jsonb,text,text) from public,anon,authenticated;

-- What p_rules (city_rules rows as JSON, already matched to one city and
-- vehicle) say about the street bay kind p_kind in p_district at p_now:
-- {"verdict": open|conditional|closed|noRule|unknownDistrict|expired|conflict,
--  "restriction": …}. Dates are Taiwan's. Rules not yet in force are
-- ignored; expired ones answer only when none is in force, and then the
-- answer is expired; rules in force that disagree are a conflict.
create function public.rule_verdict(p_rules jsonb,p_kind text,p_district text,p_now timestamptz)
returns jsonb language plpgsql immutable set search_path='' as $$
declare
  v_day date:=(p_now at time zone 'Asia/Taipei')::date;
  v_rule jsonb; v_one jsonb; v_out jsonb; v_started boolean:=false;
begin
  for v_rule in select e from jsonb_array_elements(coalesce(p_rules,'[]'::jsonb)) e loop
    continue when (v_rule->>'effective_date')::date>v_day;
    v_started:=true;
    continue when v_rule->>'expires_on' is not null and v_day>=(v_rule->>'expires_on')::date;
    v_one:=public.rule_verdict_one(v_rule,p_kind,coalesce(p_district,''));
    if v_out is null then v_out:=v_one;
    elsif v_out<>v_one then return '{"verdict":"conflict","restriction":null}';
    end if;
  end loop;
  if not v_started then return '{"verdict":"noRule","restriction":null}'; end if;
  return coalesce(v_out,'{"verdict":"expired","restriction":null}');
end $$;
-- Server-side only (the rule prescreen engine, §5.7): apps judge with the
-- Dart copy, so clients get no grant.
revoke all on function public.rule_verdict(jsonb,text,text,timestamptz) from public,anon,authenticated;

-- admin_upsert_city_rule (202610260240) on the renamed table, with
-- expires_on: optional, a date after effective_date; null clears it.
create or replace function public.admin_upsert_city_rule(
  p_city text, p_vehicle text, p_values jsonb,
  p_base_version integer default null, p_note text default '')
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp as $$
declare
  v_values jsonb:=coalesce(p_values,'{}'::jsonb);
  v_note text:=coalesce(p_note,'');
  v_fields text[]:=array['allowed_space_types','conditional_space_types','districts',
    'district_space_types','fee_note','exceptions','can_use_two_spaces','effective_date',
    'source_url','restriction','expires_on'];
  -- The original five kinds only: builds before #51 fail to parse any other
  -- kind in a rule, and the newer kinds follow the law or the bay itself.
  v_types text[]:=array['paidMotorcycle','freeMotorcycle','heavyOnly','car','offStreet'];
  v_cities text[]:=array['全國','臺北市','新北市','基隆市','桃園市','新竹市','新竹縣','苗栗縣',
    '臺中市','彰化縣','南投縣','雲林縣','嘉義市','嘉義縣','臺南市','高雄市','屏東縣',
    '宜蘭縣','花蓮縣','臺東縣','澎湖縣','金門縣','連江縣'];
  v_old city_rules_data; v_new city_rules_data; v_exists boolean; v_merged jsonb; v_bad text; v_list jsonb; v_street jsonb;
begin
  if not public.is_admin() then
    raise exception 'admin with a second factor required' using errcode='42501';
  end if;
  if p_city is null or p_city<>all(v_cities) then
    raise exception 'unknown city' using errcode='22023';
  end if;
  if p_vehicle is null or p_vehicle not in ('scooter','heavy') then
    raise exception 'unknown vehicle' using errcode='22023';
  end if;
  if jsonb_typeof(v_values)<>'object' or char_length(v_note)>500 then
    raise exception 'invalid rule' using errcode='22023';
  end if;
  select k into v_bad from jsonb_object_keys(v_values) k where k<>all(v_fields) limit 1;
  if v_bad is not null then raise exception 'field % is not editable', v_bad using errcode='22023'; end if;

  select * into v_old from city_rules_data where city=p_city and vehicle=p_vehicle for update;
  v_exists:=found;
  if p_base_version is distinct from (case when v_exists then v_old.version end) then
    raise exception 'rule changed since it was opened' using errcode='40001';
  end if;
  -- Absent fields keep the current value; a new rule must name them all
  -- except the lists, the two-space flag, the restriction and the end date.
  v_merged:=case when not v_exists then
      '{"conditional_space_types":["offStreet"],"districts":[],"district_space_types":{},"can_use_two_spaces":false,"restriction":null,"expires_on":null}'::jsonb
    else to_jsonb(v_old) end || v_values;

  foreach v_bad in array array['allowed_space_types','conditional_space_types','districts'] loop
    v_list:=v_merged->v_bad;
    if v_list is null or jsonb_typeof(v_list)<>'array' then
      raise exception '% must be a list', v_bad using errcode='22023';
    end if;
  end loop;
  if exists(select 1 from jsonb_array_elements((v_merged->'allowed_space_types')||(v_merged->'conditional_space_types')) e
            where jsonb_typeof(e)<>'string' or e#>>'{}'<>all(v_types)) then
    raise exception 'unknown space type' using errcode='22023';
  end if;
  if exists(select 1 from jsonb_array_elements_text(v_merged->'allowed_space_types') a
            join jsonb_array_elements_text(v_merged->'conditional_space_types') c on a=c)
     or (select count(*)<>count(distinct e) from jsonb_array_elements_text(v_merged->'allowed_space_types') e)
     or (select count(*)<>count(distinct e) from jsonb_array_elements_text(v_merged->'conditional_space_types') e) then
    raise exception 'a space type is listed twice' using errcode='22023';
  end if;
  -- District names: listed once, as short text.
  if exists(select 1 from jsonb_array_elements(v_merged->'districts') e
            where jsonb_typeof(e)<>'string' or char_length(e#>>'{}') not between 1 and 20)
     or jsonb_array_length(v_merged->'districts')>50
     or (select count(*)<>count(distinct e) from jsonb_array_elements_text(v_merged->'districts') e) then
    raise exception 'invalid districts' using errcode='22023';
  end if;
  v_list:=v_merged->'district_space_types';
  if v_list is null or jsonb_typeof(v_list)<>'object'
     or exists(select 1 from jsonb_each(v_list) d where d.key<>all(v_types)
       or jsonb_typeof(d.value)<>'array' or jsonb_array_length(d.value) not between 1 and 50
       or exists(select 1 from jsonb_array_elements(d.value) e
                 where jsonb_typeof(e)<>'string' or char_length(e#>>'{}') not between 1 and 20)
       or (select count(*)<>count(distinct e) from jsonb_array_elements_text(d.value) e)) then
    raise exception 'invalid district space types' using errcode='22023';
  end if;

  if jsonb_typeof(v_merged->'fee_note') is distinct from 'string'
     or char_length(v_merged->>'fee_note') not between 1 and 200 then
    raise exception 'fee note must be 1-200 characters' using errcode='22023';
  end if;
  if jsonb_typeof(v_merged->'exceptions') is distinct from 'string'
     or char_length(v_merged->>'exceptions') not between 1 and 500 then
    raise exception 'exceptions must be 1-500 characters' using errcode='22023';
  end if;
  if jsonb_typeof(v_merged->'source_url') is distinct from 'string'
     or v_merged->>'source_url' !~ '^https://[^[:space:]]+$' or char_length(v_merged->>'source_url')>500 then
    raise exception 'source url must be https' using errcode='22023';
  end if;
  if jsonb_typeof(v_merged->'can_use_two_spaces') is distinct from 'boolean' then
    raise exception 'can_use_two_spaces must be true or false' using errcode='22023';
  end if;
  foreach v_bad in array array['effective_date','expires_on'] loop
    continue when v_bad='expires_on' and jsonb_typeof(v_merged->v_bad) is not distinct from 'null';
    if jsonb_typeof(v_merged->v_bad) is distinct from 'string'
       or v_merged->>v_bad !~ '^\d{4}-\d{2}-\d{2}$' then
      raise exception '% must be YYYY-MM-DD', replace(v_bad,'_',' ') using errcode='22023';
    end if;
    begin
      perform (v_merged->>v_bad)::date;
    exception when others then
      raise exception '% must be YYYY-MM-DD', replace(v_bad,'_',' ') using errcode='22023';
    end;
  end loop;
  if (v_merged->>'expires_on')::date<=(v_merged->>'effective_date')::date then
    raise exception 'expires on must be after the effective date' using errcode='22023';
  end if;

  -- Same rule as city_rules_restriction_required, with a readable error;
  -- a restriction with no conditional street space would mean nothing.
  v_street:=(v_merged->'conditional_space_types')-'offStreet';
  if jsonb_typeof(v_merged->'restriction') not in ('string','null')
     or coalesce(v_merged->>'restriction','signage') not in ('pilot_area','signage','unverified') then
    raise exception 'unknown restriction' using errcode='22023';
  end if;
  if jsonb_array_length(v_street)>0 and v_merged->>'restriction' is null then
    raise exception 'conditional street spaces need a restriction' using errcode='23514';
  end if;
  if jsonb_array_length(v_street)=0 and v_merged->>'restriction' is not null then
    raise exception 'a restriction needs a conditional street space' using errcode='22023';
  end if;

  if v_exists and (to_jsonb(v_old)-'version')=(v_merged-'version') then
    raise exception 'rule unchanged' using errcode='22023';
  end if;

  insert into city_rules_data as r(city,vehicle,allowed_space_types,conditional_space_types,districts,
      district_space_types,fee_note,exceptions,can_use_two_spaces,effective_date,source_url,restriction,
      expires_on,version)
    values(p_city,p_vehicle,v_merged->'allowed_space_types',v_merged->'conditional_space_types',
      v_merged->'districts',v_merged->'district_space_types',v_merged->>'fee_note',v_merged->>'exceptions',
      (v_merged->>'can_use_two_spaces')::boolean,(v_merged->>'effective_date')::date,
      v_merged->>'source_url',v_merged->>'restriction',(v_merged->>'expires_on')::date,
      coalesce(v_old.version,0)+1)
    on conflict(city,vehicle) do update set
      allowed_space_types=excluded.allowed_space_types,conditional_space_types=excluded.conditional_space_types,
      districts=excluded.districts,district_space_types=excluded.district_space_types,
      fee_note=excluded.fee_note,exceptions=excluded.exceptions,can_use_two_spaces=excluded.can_use_two_spaces,
      effective_date=excluded.effective_date,source_url=excluded.source_url,restriction=excluded.restriction,
      expires_on=excluded.expires_on,version=excluded.version
      -- A rule created by someone else between the check and this insert.
      where r.version=coalesce(v_old.version,0)
    returning * into v_new;
  if v_new is null then
    raise exception 'rule changed since it was opened' using errcode='40001';
  end if;

  if v_exists then
    insert into city_rules_history(city,vehicle,version,row,replaced_by)
      values(p_city,p_vehicle,v_old.version,to_jsonb(v_old),auth.uid());
  end if;
  insert into admin_audit_log(actor,action,target_table,target_id,before,after,note)
    values(auth.uid(),'upsert_city_rule','city_rules',p_city||':'||p_vehicle,
      case when v_exists then to_jsonb(v_old) end,to_jsonb(v_new),v_note);
  return to_jsonb(v_new);
end;
$$;
