-- Zone access agrees with its condition (decision 32;
-- docs/designs/2026-10-26-parking-conditions-and-fees.md §1.3, §4.3).
-- A zone with a condition must carry an allow naming both vehicles, and its
-- access must be the one the conversion writes back from allow (and bay);
-- a condition that writes back no access, or a different access, is
-- rejected. A zone without a condition is not checked: its condition is read
-- from access, as before. Staging held no zone with a condition when this
-- was written, so validating the checks changes no row.
--
-- zone_condition_consistent() is copied from supabase/contract/parking_contract.sql,
-- generated by tool/gen_contract_sql.py; tool/test_gen_contract_sql.py checks
-- that the latest migration defining it matches the generator.

-- Whether a zone's access agrees with its condition (§1.3, decision 32): a
-- zone without a condition is not checked here; one with a condition has an
-- allow naming both vehicles, and its access is the one the condition writes
-- back. A condition that writes back no access is inconsistent.
create or replace function public.zone_condition_consistent(p_zone jsonb) returns boolean
language sql immutable set search_path='' as $$
  select coalesce(jsonb_typeof(p_zone->'condition'),'null')='null'
    or (jsonb_typeof(p_zone->'access')='string'
      and coalesce((p_zone->>'access')=public.condition_legacy_access(p_zone->'condition'),false));
$$;

-- 202610270010_parking_conditions.sql's valid_zones() plus the access check.
create or replace function public.valid_zones(p_zones jsonb) returns boolean
language sql immutable set search_path='' as $$
  select case when jsonb_typeof(p_zones) is distinct from 'array' then false else
    not exists(select 1 from jsonb_array_elements(p_zones) z
      where jsonb_typeof(z) is distinct from 'object'
        or (z ? 'fee' and not public.valid_fee(z->'fee'))
        or (z ? 'area' and not public.contract_str_in(z->'area',public.parking_contract()->'zone'->'area'))
        or (z ? 'condition' and not (public.valid_condition(z->'condition',true)
          and public.zone_condition_consistent(z)))) end;
$$;

