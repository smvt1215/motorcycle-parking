-- A fee without posted rates: a posted vehicle is dropped, as is a posted
-- period, and a by_time left without periods; null when no vehicle is left.
-- Kept (not granted) for imports and tests; zones_without_posted() does the
-- same for every zone's fee.
create function public.fee_without_posted(p_fee jsonb) returns jsonb
language sql immutable set search_path='' as $$
  select nullif(coalesce(jsonb_object_agg(v.key,v.rate),'{}'::jsonb),'{}'::jsonb)
  from (
    select e.key,case when e.value->>'mode'='by_time' then jsonb_set(e.value,'{periods}',
        coalesce((select jsonb_agg(p order by n) from jsonb_array_elements(e.value->'periods') with ordinality x(p,n)
          where p->'rate'->>'mode' is distinct from 'posted'),'[]'::jsonb))
      else e.value end as rate
    from jsonb_each(p_fee) e
    where e.value->>'mode' is distinct from 'posted'
  ) v
  where v.rate->>'mode'<>'by_time' or jsonb_array_length(v.rate->'periods')>0;
$$;
revoke execute on function public.fee_without_posted(jsonb) from public,anon,authenticated;

create function public.zones_without_posted(p_zones jsonb) returns jsonb
language sql immutable set search_path='' as $$
  select case when jsonb_typeof(p_zones)<>'array' then p_zones
    else coalesce((select jsonb_agg(case when jsonb_typeof(z->'fee')='object' and z->'fee'<>'{}'::jsonb
        then case when public.fee_without_posted(z->'fee') is null then z-'fee'
          else jsonb_set(z,'{fee}',public.fee_without_posted(z->'fee')) end
        else z end order by n)
      from jsonb_array_elements(p_zones) with ordinality x(z,n)),'[]'::jsonb) end;
$$;
revoke execute on function public.zones_without_posted(jsonb) from public,anon,authenticated;

