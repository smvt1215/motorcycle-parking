-- Fees v2, core (docs/designs/2026-10-26-parking-conditions-and-fees.md §2,
-- §5.5, §7 items 5, 11, 12, 15; stack C, C3 first layer).
--
-- - valid_fee() becomes the v2 contract: the car rate, the new rate keys,
--   by_time with up to 6 periods, renew and cross_period. Every stored fee
--   stays valid: v2 accepts everything v1 did.
-- - fee_note_of() writes the new sentences (§2.5): renew and cross_period in
--   words, by_time period by period, and a heavy rate following another
--   vehicle as the amounts worked out, never 「比照」 (#140). Every row with a
--   fee gets the new sentence in one statement per table.
-- - fee_source_text keeps the original fee text (§5.5, §7 items 5 and 12):
--   rows whose fee_note was not their fee's sentence (imported or converted
--   notes) move it there. Only imports and administrators write it; the app
--   never reads it (community_spots grants no column of it).
-- - posted (依現場公告) reads as unconfirmed (§7 item 15): stored ones are
--   dropped, and a fee left with no vehicle becomes null. The contract still
--   accepts posted from older builds.
-- - fee_note may be longer than 200 characters only when it is its fee's
--   sentence, up to fee_note_max_length(), which tool/fee_text.py works out
--   from the contract. Free text keeps the 200 bound.
--
-- The two sections below are copied from supabase/contract/parking_contract.sql,
-- generated by tool/gen_contract_sql.py; tool/test_gen_contract_sql.py checks
-- the latest migration defining each function matches.

