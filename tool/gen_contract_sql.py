"""Generate SQL from the parking contract.

SQL cannot read supabase/functions/_shared/parking_contract.json at run time,
so this writes (docs/designs/2026-10-26-parking-conditions-and-fees.md §4.1):

- supabase/contract/parking_contract.sql: valid_condition(),
  condition_space_type() and the fee v2 valid_fee(), with the contract
  embedded as their key table. Not a migration: nothing applies it; the
  migrations that add the columns copy it.
- supabase/tests/parking_contract_test.sql: pgTAP that creates the same
  functions in pg_temp inside its transaction and runs
  parking_contract_cases.json against them, then rolls back.

Both outputs are committed; CI regenerates them and fails on any diff.
Usage: python3 tool/gen_contract_sql.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "supabase/functions/_shared/parking_contract.json"
CASES = ROOT / "supabase/functions/_shared/parking_contract_cases.json"
FUNCTIONS_OUT = ROOT / "supabase/contract/parking_contract.sql"
TEST_OUT = ROOT / "supabase/tests/parking_contract_test.sql"

HEADER = """\
-- Generated by tool/gen_contract_sql.py from
-- supabase/functions/_shared/parking_contract.json{cases}. Do not edit;
-- change the contract and rerun the generator.
"""

# {s} is the schema: public for the contract file, pg_temp for the test.
TEMPLATE = r"""
create or replace function {s}.parking_contract() returns jsonb
language sql immutable set search_path='' as $contract$
  select $json${contract}$json$::jsonb;
$contract$;

-- A whole number in range; CASE so a string returns false, not a cast error.
create or replace function {s}.contract_whole(p jsonb,p_min numeric,p_max numeric) returns boolean
language sql immutable set search_path='' as $$
  select case when jsonb_typeof(p)='number'
    then (p::text)::numeric=trunc((p::text)::numeric) and (p::text)::numeric between p_min and p_max
    else false end;
$$;

create or replace function {s}.contract_str_in(p jsonb,p_list jsonb) returns boolean
language sql immutable set search_path='' as $$
  select coalesce(jsonb_typeof(p)='string' and p_list ? (p#>>'{{}}'),false);
$$;

-- A non-empty array of distinct strings drawn from p_list.
create or replace function {s}.contract_subset(p jsonb,p_list jsonb) returns boolean
language sql immutable set search_path='' as $$
  select case when jsonb_typeof(p)='array' then jsonb_array_length(p)>0
    and not exists(select 1 from jsonb_array_elements(p) e where not {s}.contract_str_in(e,p_list))
    and (select count(distinct e) from jsonb_array_elements(p) e)=jsonb_array_length(p)
    else false end;
$$;

create or replace function {s}.contract_date(p jsonb) returns boolean
language sql immutable set search_path='' as $$
  select coalesce(jsonb_typeof(p)='string'
    and (p#>>'{{}}') ~ ({s}.parking_contract()->'date'->>'pattern')
    and pg_input_is_valid(p#>>'{{}}','date'),false);
$$;

-- days, from and to of a schedule slot or a fee period.
create or replace function {s}.contract_slot_times(p jsonb) returns boolean
language sql immutable set search_path='' as $$
  select coalesce(case when jsonb_typeof(p->'days')='string'
      then {s}.contract_str_in(p->'days',{s}.parking_contract()->'time'->'days')
      else {s}.contract_subset(p->'days',{s}.parking_contract()->'time'->'weekdays') end
    and jsonb_typeof(p->'from')='string' and jsonb_typeof(p->'to')='string'
    and (p->>'from') ~ ({s}.parking_contract()->'time'->>'pattern')
    and (p->>'to') ~ ({s}.parking_contract()->'time'->>'pattern')
    and p->>'from'<>p->>'to',false);
$$;

-- An object with exactly the listed keys.
create or replace function {s}.contract_exact_keys(p jsonb,p_keys jsonb) returns boolean
language sql immutable set search_path='' as $$
  select case when jsonb_typeof(p)='object' then
    not exists(select 1 from jsonb_object_keys(p) k where not p_keys ? k)
    and not exists(select 1 from jsonb_array_elements_text(p_keys) k where not p ? k)
    else false end;
$$;

-- A bay's or a zone's condition (§1.2, §4.3), the same rules as
-- validCondition in validate.ts and lib/models/parking_condition.dart.
create or replace function {s}.valid_condition(p jsonb,p_zone boolean default false) returns boolean
language plpgsql immutable set search_path='' as $$
declare
  c jsonb:={s}.parking_contract()->'condition';
  l jsonb; v jsonb; spec jsonb; f record; kinds text[]:='{{}}';
begin
  if jsonb_typeof(p) is distinct from 'object' or p='{{}}'::jsonb then return false; end if;
  if exists(select 1 from jsonb_object_keys(p) k
      where not (c->'keys' ? k or (p_zone and c->'zone_keys' ? k))) then return false; end if;
  if (p ? 'bay' and not {s}.contract_str_in(p->'bay',c->'bay'))
    or (p ? 'use' and not {s}.contract_str_in(p->'use',c->'use'))
    or (p ? 'share' and not (jsonb_typeof(p->'share')='string' and c->'share' ? (p->>'share')))
    or (p ? 'charge' and not {s}.contract_str_in(p->'charge',c->'charge')) then return false; end if;
  if not p_zone and not p ? 'bay' then return false; end if;
  if (p ? 'share')<>coalesce(p->>'use'='share',false) then return false; end if;
  if p ? 'share' and (p->>'bay') is distinct from (c->'share'->>(p->>'share')) then return false; end if;

  if p ? 'limits' then
    if jsonb_typeof(p->'limits') is distinct from 'array'
      or jsonb_array_length(p->'limits') not between 1 and (select count(*) from jsonb_object_keys(c->'limits'))
    then return false; end if;
    for l in select e from jsonb_array_elements(p->'limits') e loop
      if jsonb_typeof(l) is distinct from 'object' or jsonb_typeof(l->'kind') is distinct from 'string'
        or not c->'limits' ? (l->>'kind') or (l->>'kind')=any(kinds) then return false; end if;
      kinds:=kinds||(l->>'kind');
      spec:=c->'limits'->(l->>'kind');
      for f in select key,value from jsonb_each(l) loop
        continue when f.key='kind' or spec->'required' ? f.key;
        if not spec->'optional' ? f.key or not {s}.contract_whole(f.value,
            (spec->'optional'->f.key->>'min')::numeric,(spec->'optional'->f.key->>'max')::numeric)
        then return false; end if;
      end loop;
      if exists(select 1 from jsonb_array_elements_text(spec->'required') r where not l ? r) then return false; end if;
      if l ? 'vehicle' and not {s}.contract_str_in(l->'vehicle',c->'special_vehicles') then return false; end if;
    end loop;
  end if;
  if not p_zone and p->>'bay'='motorcycle' and not p ? 'charge'
    and not kinds && array(select jsonb_array_elements_text(c->'street_charge_optional_with'))
  then return false; end if;

  if p ? 'allow' then
    v:=p->'allow';
    if jsonb_typeof(v) is distinct from 'object' or v='{{}}'::jsonb
      or exists(select 1 from jsonb_each(v) e where not c->'allow_keys' ? e.key or jsonb_typeof(e.value)<>'boolean')
    then return false; end if;
    if v->'scooter'='true'::jsonb and p->>'bay'='heavy' then return false; end if;
  end if;

  if p ? 'schedule' then
    if jsonb_typeof(p->'schedule') is distinct from 'array'
      or jsonb_array_length(p->'schedule') not between 1 and (c->'schedule'->>'max_entries')::integer
    then return false; end if;
    for l in select e from jsonb_array_elements(p->'schedule') e loop
      if not {s}.contract_exact_keys(l,'["days","from","to","vehicles"]') or not {s}.contract_slot_times(l)
        or not {s}.contract_subset(l->'vehicles',c->'schedule'->'vehicles') then return false; end if;
    end loop;
  end if;

  if p ? 'basis' then
    v:=p->'basis';
    if jsonb_typeof(v) is distinct from 'object'
      or exists(select 1 from jsonb_object_keys(v) k where not c->'basis'->'keys' ? k) then return false; end if;
    -- Reserved until photo evidence ships (verification plan P2).
    if exists(select 1 from jsonb_array_elements_text(c->'basis'->'reserved') r
        where coalesce(jsonb_typeof(v->r),'null')<>'null') then return false; end if;
    if not exists(select 1 from jsonb_array_elements_text(c->'basis'->'required_one_of') r
        where coalesce(jsonb_typeof(v->r),'null')<>'null') then return false; end if;
    if v ? 'source_url' and not coalesce(jsonb_typeof(v->'source_url')='string'
        and char_length(v->>'source_url')<=(c->'basis'->'source_url'->>'max_length')::integer
        and (v->>'source_url') ~ (c->'basis'->'source_url'->>'pattern'),false) then return false; end if;
    if (coalesce(jsonb_typeof(v->'effective_date'),'null')<>'null' and not {s}.contract_date(v->'effective_date'))
      or (coalesce(jsonb_typeof(v->'expires_on'),'null')<>'null' and not {s}.contract_date(v->'expires_on'))
    then return false; end if;
    if jsonb_typeof(v->'effective_date')='string' and jsonb_typeof(v->'expires_on')='string'
      and (v->>'expires_on') collate "C"<=(v->>'effective_date') collate "C" then return false; end if;
  end if;
  return true;
end;
$$;

-- The legacy space_type a condition is stored under (§1.3): the first
-- to_space_type rule that matches, or null.
create or replace function {s}.condition_space_type(p jsonb,p_off_street boolean) returns text
language plpgsql immutable set search_path='' as $$
declare r jsonb; w jsonb;
begin
  for r in select e from jsonb_array_elements({s}.parking_contract()->'conversion'->'to_space_type') e loop
    w:=r->'when';
    if (not w ? 'placement' or p_off_street)
      and (not w ? 'limit' or exists(select 1 from jsonb_array_elements(
        case when jsonb_typeof(p->'limits')='array' then p->'limits' else '[]'::jsonb end) l
        where l->>'kind'=w->>'limit'))
      and (not w ? 'share' or p->>'share' is not distinct from w->>'share')
      and (not w ? 'bay' or p->>'bay' is not distinct from w->>'bay')
      and (not w ? 'charge' or p->>'charge' is not distinct from w->>'charge')
    then return r->>'space_type'; end if;
  end loop;
  return null;
end;
$$;

-- The keys of p (besides mode) against a {{required, optional}} spec: ranges
-- (max may name a sibling key), enums, extension and periods.
create or replace function {s}.contract_fee_fields(p jsonb,p_spec jsonb,p_vehicle text) returns boolean
language plpgsql immutable set search_path='' as $$
declare fee jsonb:={s}.parking_contract()->'fee'; f record; fs jsonb; hi numeric;
begin
  if jsonb_typeof(p) is distinct from 'object' then return false; end if;
  for f in select key,value from jsonb_each(p) loop
    continue when f.key='mode';
    fs:=coalesce(p_spec->'required'->f.key,p_spec->'optional'->f.key);
    if fs is null then return false; end if;
    if jsonb_typeof(fs)='object' then
      if jsonb_typeof(fs->'max')='string' then
        hi:=case when {s}.contract_whole(p->(fs->>'max'),0,1e9) then (p->>(fs->>'max'))::numeric end;
        if hi is null then return false; end if;
      else hi:=(fs->>'max')::numeric; end if;
      if not {s}.contract_whole(f.value,(fs->>'min')::numeric,hi) then return false; end if;
    elsif fee->'enums' ? (fs#>>'{{}}') then
      if not {s}.contract_str_in(f.value,fee->'enums'->(fs#>>'{{}}')) then return false; end if;
    elsif fs#>>'{{}}'='extension' then
      if jsonb_typeof(f.value) is distinct from 'object' or (f.value ? 'mode')
        or not {s}.contract_fee_fields(f.value,fee->'extension',p_vehicle) then return false; end if;
    elsif fs#>>'{{}}'='periods' then
      if jsonb_typeof(f.value) is distinct from 'array'
        or jsonb_array_length(f.value) not between 1 and (fee->'periods'->>'max_entries')::integer
        or exists(select 1 from jsonb_array_elements(f.value) e
          where not {s}.contract_exact_keys(e,fee->'periods'->'keys') or not {s}.contract_slot_times(e)
            or not {s}.contract_fee_rate(e->'rate',p_vehicle,true))
      then return false; end if;
    else return false; end if;
  end loop;
  return not exists(select 1 from jsonb_object_keys(p_spec->'required') r where not p ? r);
end;
$$;

-- One vehicle's rate (§2.2); a period's rate may not follow or nest by_time.
create or replace function {s}.contract_fee_rate(p jsonb,p_vehicle text,p_nested boolean) returns boolean
language plpgsql immutable set search_path='' as $$
declare fee jsonb:={s}.parking_contract()->'fee'; m text;
begin
  if jsonb_typeof(p) is distinct from 'object' or jsonb_typeof(p->'mode') is distinct from 'string' then return false; end if;
  m:=p->>'mode';
  if fee->'follow'->'modes' ? m then
    return not p_nested and fee->'follow'->'vehicles' ? p_vehicle
      and {s}.contract_fee_fields(p,jsonb_build_object('required','{{}}'::jsonb,'optional',fee->'follow'->'optional'),p_vehicle);
  end if;
  if not fee->'modes' ? m or (p_nested and not fee->'periods'->'nested_modes' ? m) then return false; end if;
  return {s}.contract_fee_fields(p,fee->'modes'->m,p_vehicle);
end;
$$;

-- Fee v2 (§2.2): a rate per vehicle; a missing vehicle is unconfirmed.
create or replace function {s}.valid_fee(p jsonb) returns boolean
language plpgsql immutable set search_path='' as $$
declare fee jsonb:={s}.parking_contract()->'fee';
begin
  if jsonb_typeof(p) is distinct from 'object' then return false; end if;
  return pg_column_size(p)<=(fee->>'max_bytes')::integer
    and not exists(select 1 from jsonb_object_keys(p) k where not fee->'vehicles' ? k)
    and not exists(select 1 from jsonb_object_keys(p) k where not {s}.contract_fee_rate(p->k,k,false));
end;
$$;
"""


def strip_comments(value):
    """Drop documentation keys; the SQL only needs the rules."""
    if isinstance(value, dict):
        return {k: strip_comments(v) for k, v in value.items() if k != "comment"}
    if isinstance(value, list):
        return [strip_comments(v) for v in value]
    return value


def literal(value):
    """A dollar-quoted jsonb literal."""
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if "$j$" in text:
        raise ValueError("value contains the $j$ quote")
    return f"$j${text}$j$::jsonb"


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def functions_sql(contract, schema):
    text = json.dumps(strip_comments(contract), ensure_ascii=False, separators=(",", ":"))
    if "$json$" in text:
        raise ValueError("contract contains the $json$ quote")
    # Escape braces in the data before formatting the template.
    body = TEMPLATE.replace("{contract}", "\0").format(s=schema)
    return body.replace("\0", text)


def test_sql(contract, cases):
    lines = [
        HEADER.format(cases=" and parking_contract_cases.json"),
        "begin;",
        "create extension if not exists pgtap with schema extensions;",
        "set search_path=public,extensions;",
        "select no_plan();",
        "-- The generated functions, in pg_temp so the shared schema is untouched.",
        functions_sql(contract, "pg_temp"),
        "-- conditions: valid_condition()",
    ]
    for c in cases["conditions"]:
        zone = "true" if c["zone"] else "false"
        lines.append(
            f"select is(pg_temp.valid_condition({literal(c['condition'])},{zone}),"
            f"{'true' if c['valid'] else 'false'},{quote('condition: ' + c['name'])});"
        )
    lines.append("-- legacy: condition_space_type()")
    for c in cases["legacy"]:
        off = "true" if c["off_street"] else "false"
        want = "null::text" if c["space_type"] is None else quote(c["space_type"])
        lines.append(
            f"select is(pg_temp.condition_space_type({literal(c['condition'])},{off}),"
            f"{want},{quote('space type: ' + c['name'])});"
        )
    lines.append("-- fees: valid_fee() v2")
    for c in cases["fees"]:
        lines.append(
            f"select is(pg_temp.valid_fee({literal(c['fee'])}),"
            f"{'true' if c['valid'] else 'false'},{quote('fee: ' + c['name'])});"
        )
    lines += ["select * from finish();", "rollback;", ""]
    return "\n".join(lines)


def generate():
    contract = json.loads(CONTRACT.read_text())
    cases = json.loads(CASES.read_text())
    return {
        FUNCTIONS_OUT: HEADER.format(cases="") + functions_sql(contract, "public"),
        TEST_OUT: test_sql(contract, cases),
    }


def main():
    for path, text in generate().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


if __name__ == "__main__":
    main()
