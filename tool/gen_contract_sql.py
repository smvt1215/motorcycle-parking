def rule_verdict_sql(vectors):
    lines = [
        HEADER.replace("parking_contract.json{cases}", "rule_verdict_cases.json"),
        "begin;",
        "create extension if not exists pgtap with schema extensions;",
        "set search_path=public,extensions;",
        "select no_plan();",
    ]
    rules = vectors["rules"]
    for c in vectors["cases"]:
        want = {"verdict": c["verdict"], "restriction": c["restriction"]}
        lines.append(
            f"select is(public.rule_verdict({literal([rules[r] for r in c['rules']])},"
            f"{quote(c['kind'])},{quote(c['district'])},{quote(c['now'])}::timestamptz),"
            f"{literal(want)},{quote('rule verdict: ' + c['name'])});"
        )
    lines += ["select * from finish();", "rollback;", ""]
    return "\n".join(lines)


