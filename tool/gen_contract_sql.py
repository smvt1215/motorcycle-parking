def strip_comments(value):
    """Drop documentation keys; the SQL only needs the rules."""
    if isinstance(value, dict):
        return {k: strip_comments(v) for k, v in value.items() if k != "comment"}
    if isinstance(value, list):
        return [strip_comments(v) for v in value]
    return value


def literal(value):
    """A dollar-quoted jsonb literal."""
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if "$j$" in text:
        raise ValueError("value contains the $j$ quote")
    return f"$j${text}$j$::jsonb"


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def functions_sql(contract, schema):
    text = json.dumps(strip_comments(contract), ensure_ascii=False, separators=(",", ":"))
    if "$json$" in text:
        raise ValueError("contract contains the $json$ quote")
    # Escape braces in the data before formatting the template.
    body = TEMPLATE.replace("{contract}", "\0").format(
        s=schema, fee_note_max=fee_text.fee_note_max_length(contract["fee"]))
    return body.replace("\0", text)


