import json
import unittest

import gen_contract_sql as gen


class GenContractSqlTest(unittest.TestCase):
    def test_committed_outputs_match_the_contract(self):
        for path, text in gen.generate().items():
            with self.subTest(path=path.name):
                self.assertEqual(path.read_text(), text,
                                 "rerun python3 tool/gen_contract_sql.py")

    def test_the_test_file_only_creates_functions_in_pg_temp(self):
        outputs = gen.generate()
        test = outputs[gen.TEST_OUT]
        self.assertTrue(test.startswith("-- Generated by tool/gen_contract_sql.py"))
        self.assertIn("\nbegin;\n", test)
        self.assertTrue(test.rstrip().endswith("rollback;"))
        self.assertNotIn("public.", test)
        creates = [line for line in test.splitlines() if line.startswith("create or replace function")]
        self.assertTrue(creates)
        self.assertTrue(all(line.startswith("create or replace function pg_temp.") for line in creates))
        self.assertNotIn("pg_temp", outputs[gen.FUNCTIONS_OUT])

    def test_every_case_becomes_an_assertion(self):
        cases = json.loads(gen.CASES.read_text())
        test = gen.generate()[gen.TEST_OUT]
        total = sum(len(cases[k]) for k in ("conditions", "legacy", "fees"))
        self.assertEqual(test.count("select is("), total)

    def test_the_embedded_contract_drops_comments(self):
        self.assertEqual(gen.strip_comments({"comment": "x", "a": [{"comment": 1, "b": 2}]}),
                         {"a": [{"b": 2}]})

    def test_quotes_cannot_be_broken_by_data(self):
        with self.assertRaises(ValueError):
            gen.literal({"name": "$j$"})
        self.assertEqual(gen.quote("車友's"), "'車友''s'")


if __name__ == "__main__":
    unittest.main()
