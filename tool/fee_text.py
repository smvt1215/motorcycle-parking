"""The fee_note sentence of a fee (docs/designs/2026-10-26-parking-conditions-and-fees.md
§2.2, §2.5, §7 items 11, 14, 15, 34), as the generator needs it to bound
its length.

The same sentences are written by fee_note_of() (SQL, generated by
tool/gen_contract_sql.py), feeNoteOf in lib/models/fee.dart and feeNoteOf
in supabase/functions/_shared/fee.ts; parking_contract_cases.json pins them
for all four. Rules:

- The known vehicles in the order 機車, 大型重機, 汽車, joined by 「；」,
  then 大型重機費率未確認 when the heavy rate is unknown; no known vehicle
  at all: 請依現場公告.
- A missing vehicle, a `posted` rate and a `by_time` rate whose every
  period is `posted` read as unconfirmed.
- Heavy bikes following another vehicle show the amounts worked out
  (factor_pct applied to amount, daily_cap and extension amount), never
  「比照」; when the followed vehicle is unconfirmed: 大型重機費率未提供.
- by_time lists periods grouped by the set of days they cover, in order of
  first appearance; each group is labelled 每天, 平日, 假日 or the days it
  names (週一、週三), then a colon. A last clause states how a stay
  crossing periods is charged when cross_period is set or at least two
  periods charge per visit.
"""

WEEKDAYS = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]
DAY_NAMES = "一二三四五六日"
DAY_MASKS = {"all": 127, "weekday": 31, "holiday": 96}
RESET = {
    "calendar_day": "零時重算",
    "rolling_24h": "停滿 24 小時重算",
    "per_entry": "每次進場重算",
}
CROSS = {"each_period": "跨時段分別計費", "entry_only": "依進場時段計費"}
CROSS_UNCONFIRMED = "跨時段計費方式未確認"
DEFAULT_NOTE = "請依現場公告"


def _int(v):
    return int(v)


def money(amount, pct=100):
    v = _int(amount) * pct
    whole, rem = divmod(v, 100)
    if rem == 0:
        return str(whole)
    if rem % 10 == 0:
        return f"{whole}.{rem // 10}"
    return f"{whole}.{rem:02d}"


def span(minutes):
    m = _int(minutes)
    return f"{m // 60} 小時" if m % 60 == 0 else f"{m} 分鐘"


def every(minutes):
    m = _int(minutes)
    if m == 60:
        return "每小時"
    return f"每 {m // 60} 小時" if m % 60 == 0 else f"每 {m} 分鐘"


def day_mask(days):
    if isinstance(days, str):
        return DAY_MASKS[days]
    return sum(1 << WEEKDAYS.index(d) for d in days)


def day_label(mask):
    if mask == 127:
        return "每天"
    if mask == 31:
        return "平日"
    if mask == 96:
        return "假日"
    return "、".join("週" + DAY_NAMES[i] for i in range(7) if mask & (1 << i))


def period_time(p):
    if "from" not in p:
        return "全天"
    if p["from"] < p["to"]:
        return f"{p['from']}–{p['to']}"
    return f"{p['from']}–隔日 {p['to']}"


def rate_text(r, pct=100):
    """One rate's words, or None when it reads as unconfirmed."""
    if not isinstance(r, dict):
        return None
    mode = r.get("mode")
    if mode == "free":
        return "免費"
    if mode == "hourly":
        text = f"{every(r['per_minutes'])} {money(r['amount'], pct)} 元"
        if "free_minutes" in r:
            text = f"首 {span(r['free_minutes'])} 0 元，之後{text}"
        if "unit_minutes" in r:
            text += f"（以 {span(r['unit_minutes'])}計）"
        if "daily_cap" in r:
            reset = RESET.get(r.get("cap_reset"), "上限計算方式未確認")
            text += f"，當日上限 {money(r['daily_cap'], pct)} 元（{reset}）"
        return text
    if mode == "per_visit":
        if _int(r["amount"]) == 0 and "max_minutes" in r:
            text = f"首 {span(r['max_minutes'])} 0 元"
        else:
            notes = []
            if "max_minutes" in r:
                notes.append(f"{span(r['max_minutes'])}內")
            renew = r.get("renew")
            if renew is None:
                notes.append("隔日是否另計未確認")
            text = f"每次 {money(r['amount'], pct)} 元"
            if notes:
                text += "（" + "，".join(notes) + "）"
            if renew == "midnight":
                text += "，隔日另計"
            elif renew == "none":
                text += "，有效時間內只收一次" if "max_minutes" in r else "，停多久都只收一次"
        ext = r.get("extension")
        if isinstance(ext, dict):
            text += f"，可付 {money(ext['amount'], pct)} 元延長 {_int(ext['max_times'])} 次"
            text += f"（每次 {span(ext['minutes'])}）" if "minutes" in ext else "（延長時間未確認）"
        return text
    if mode == "daily":
        text = f"每日 {money(r['amount'], pct)} 元"
        if r.get("cap_reset") in RESET:
            text += f"（{RESET[r['cap_reset']]}）"
        return text
    if mode == "by_time":
        periods = [(p, rate_text(p["rate"], pct)) for p in r["periods"]]
        periods = [(p, t) for p, t in periods if t is not None]
        if not periods:
            return None
        groups = []
        for p, t in periods:
            mask = day_mask(p["days"])
            for g in groups:
                if g[0] == mask:
                    g[1].append(f"{period_time(p)} {t}")
                    break
            else:
                groups.append((mask, [f"{period_time(p)} {t}"]))
        parts = []
        for mask, items in groups:
            parts.append(day_label(mask) + "：" + "；".join(items))
        text = "；".join(parts)
        visits = sum(1 for p, _ in periods if p["rate"].get("mode") == "per_visit")
        if "cross_period" in r:
            text += "；" + CROSS[r["cross_period"]]
        elif visits >= 2:
            text += "；" + CROSS_UNCONFIRMED
        return text
    return None  # posted, a follow out of place, or unknown


def fee_note_of(fee):
    """The fee_note text of a valid fee."""
    fee = fee if isinstance(fee, dict) else {}
    s = rate_text(fee.get("scooter"))
    c = rate_text(fee.get("car"))
    heavy = fee.get("heavy")
    h, unprovided = None, False
    if isinstance(heavy, dict) and heavy.get("mode") in ("same_as_scooter", "same_as_car"):
        target = fee.get("scooter" if heavy["mode"] == "same_as_scooter" else "car")
        h = rate_text(target, _int(heavy.get("factor_pct", 100)))
        unprovided = h is None
    else:
        h = rate_text(heavy)
    if s is None and h is None and c is None and not unprovided:
        return DEFAULT_NOTE
    parts = []
    if s is not None:
        parts.append("機車" + s)
    if h is not None or unprovided:
        parts.append("大型重機" + ("費率未提供" if unprovided else h))
    if c is not None:
        parts.append("汽車" + c)
    if h is None and not unprovided:
        parts.append("大型重機費率未確認")
    return "；".join(parts)


# ---- The longest sentence the contract allows (§2.5 長度上限) ----

def _nested_candidates(fee_contract, amount):
    """The longest-reading choices for one period's rate, per mode."""
    hi = {k: v["max"] for k, v in fee_contract["modes"]["hourly"]["required"].items()}
    minutes = 1439  # the longest span within 1–1440 (「1439 分鐘」)
    ext = {"amount": amount, "max_times": fee_contract["extension"]["required"]["max_times"]["max"],
           "minutes": minutes}
    out = [
        {"mode": "hourly", "amount": amount, "per_minutes": minutes, "unit_minutes": minutes,
         "free_minutes": minutes, "daily_cap": amount},
        {"mode": "daily", "amount": amount, "cap_reset": "rolling_24h"},
        {"mode": "free"},
    ]
    for renew in (None, "none", "midnight"):
        r = {"mode": "per_visit", "amount": amount, "max_minutes": minutes, "extension": ext}
        if renew:
            r["renew"] = renew
        out.append(r)
    assert hi["per_minutes"] >= minutes
    return out


def _longest_by_time(fee_contract, amount, pct):
    """by_time with the most periods, each the longest rate under a day
    set of its own with the longest label and an overnight time."""
    count = fee_contract["periods"]["max_entries"]
    # Six-day sets: none is 平日, 假日 or 每天, so each gets the longest label.
    day_sets = [[d for d in WEEKDAYS if d != skip] for skip in reversed(WEEKDAYS)][:count]
    candidates = _nested_candidates(fee_contract, amount)
    best_visit = max((c for c in candidates if c["mode"] == "per_visit"),
                     key=lambda c: len(rate_text(c, pct)))
    best_other = max((c for c in candidates if c["mode"] != "per_visit"),
                     key=lambda c: len(rate_text(c, pct)))
    best = None
    for visits in range(count + 1):
        for cross in (None, "each_period", "entry_only"):
            rates = [best_visit] * visits + [best_other] * (count - visits)
            r = {"mode": "by_time", "periods": [
                {"days": days, "from": "23:00", "to": "22:00", "rate": rate}
                for days, rate in zip(day_sets, rates)]}
            if cross:
                r["cross_period"] = cross
            if best is None or len(rate_text(r, pct)) > len(rate_text(best, pct)):
                best = r
    return best


def longest_fee(fee_contract):
    """A valid fee whose sentence is as long as any the contract allows:
    every vehicle by_time, the heavy one following the car at a factor that
    leaves two decimals on each amount (9999 × 999% = 99890.01)."""
    amount = fee_contract["modes"]["per_visit"]["required"]["amount"]["max"]
    pct = fee_contract["follow"]["optional"]["factor_pct"]["max"] - 1
    candidates = [
        {"scooter": _longest_by_time(fee_contract, amount, 100),
         "heavy": _longest_by_time(fee_contract, amount, 100),
         "car": _longest_by_time(fee_contract, amount, 100)},
        {"scooter": _longest_by_time(fee_contract, amount, 100),
         "heavy": {"mode": "same_as_car", "factor_pct": pct},
         "car": _longest_by_time(fee_contract, amount - 1, pct)},
    ]
    return max(candidates, key=lambda f: len(fee_note_of(f)))


def fee_note_max_length(fee_contract):
    return len(fee_note_of(longest_fee(fee_contract)))


# ---- The largest fee the contract allows (the size bound, §2.2) ----

def largest_fee(fee_contract):
    """A valid fee as large as any the contract allows: every vehicle
    by_time with the most periods, each on every weekday as a list, with
    times, cross_period, and the nested rate with the most keys at their
    largest values written with a decimal point (20.0 is valid and stores
    larger). valid_fee()'s max_bytes must hold it, so no side refuses a fee
    of a valid shape for its size."""
    whole = lambda n: float(n)
    amount = whole(fee_contract["modes"]["per_visit"]["required"]["amount"]["max"])
    minutes = whole(1440)
    rates = [
        {"mode": "per_visit", "amount": amount, "max_minutes": minutes, "renew": "midnight",
         "extension": {"amount": amount, "max_times": whole(10), "minutes": minutes}},
        {"mode": "hourly", "amount": amount, "per_minutes": minutes, "unit_minutes": minutes,
         "free_minutes": minutes, "daily_cap": amount, "cap_reset": "calendar_day"},
    ]
    def by_time(rate):
        return {"mode": "by_time", "cross_period": "each_period", "periods": [
            {"days": list(WEEKDAYS), "from": "23:00", "to": "22:00", "rate": rate}
            for _ in range(fee_contract["periods"]["max_entries"])]}
    import json as _json
    best = max(rates, key=lambda r: len(_json.dumps(r)))
    return {v: by_time(best) for v in fee_contract["vehicles"]}
