/// Which days are 平日 and which 假日 (decision 61): the government office
/// calendar (行政院人事行政總處「政府行政機關辦公日曆表」, data.gov.tw 14718),
/// where 放假 days — weekends, national holidays, 補假 — are 假日 and the
/// rest, 補班 Saturdays included, 平日. Years the calendar does not cover
/// fall back on 週六日 as 假日, and say so ([HolidayCalendar.covers]).
///
/// The backend's `holidays` table (supabase/migrations/202610270150_holidays.sql)
/// holds every day; clients read the days that differ from 週六日放假 through
/// `holiday_calendar()`, and the app ships the current and the next year
/// (holidays_builtin.g.dart, generated by tool/holidays.py) for when the
/// backend cannot be read. Pure Dart, shared by the app and the admin site.
library;

import 'parking_condition.dart' show scheduleWeekdays;

part 'holidays_builtin.g.dart';

/// One calendar day as fee periods and schedule slots read it.
typedef CalendarDay = ({
  /// 0 is Monday, as `scheduleWeekdays`.
  int weekday,

  /// 假日: 是否放假 = 2, or 週六日 in a year the calendar lacks.
  bool off,

  /// False when [off] is only the weekend fallback.
  bool known,
});

class HolidayCalendar {
  const HolidayCalendar({
    this.years = const {},
    this.off = const {},
    this.work = const {},
  });

  /// Gregorian years the calendar covers.
  final Set<int> years;

  /// `YYYY-MM-DD` of the weekdays that are off (national holidays, 補假).
  final Set<String> off;

  /// `YYYY-MM-DD` of the weekend days that are workdays (補班).
  final Set<String> work;

  /// The calendar in use: the app's fallback until the backend's arrives
  /// (AppStore), replaced as a whole so a judgment never mixes the two.
  static HolidayCalendar current = builtinHolidays;

  /// No data: every year falls back on the weekend.
  static const none = HolidayCalendar();

  bool covers(int year) => years.contains(year);

  /// [date]'s day; only its year, month and day are read.
  CalendarDay dayOf(DateTime date) {
    final d = DateTime.utc(date.year, date.month, date.day);
    final weekday = d.weekday - 1;
    final weekend = weekday >= 5;
    if (!covers(d.year)) return (weekday: weekday, off: weekend, known: false);
    final key = _ymd(d);
    return (
      weekday: weekday,
      off: weekend ? !work.contains(key) : off.contains(key),
      known: true,
    );
  }

  /// The calendar `holiday_calendar()` returns: `years`, and the `off` and
  /// `work` days; null when [json] is not one.
  static HolidayCalendar? fromJson(Object? json) {
    if (json is! Map) return null;
    final years = json['years'], off = json['off'], work = json['work'];
    if (years is! List || off is! List || work is! List) return null;
    if (![...off, ...work].every((d) => d is String && _date.hasMatch(d))) {
      return null;
    }
    return HolidayCalendar(
      years: {for (final y in years) ?(y is num ? y.toInt() : null)},
      off: {for (final d in off) d as String},
      work: {for (final d in work) d as String},
    );
  }

  /// This calendar with [other]'s years in place of its own; the years
  /// [other] lacks stay as they are, so a backend missing next year keeps
  /// the app's copy of it.
  HolidayCalendar overriddenBy(HolidayCalendar other) {
    bool keep(String d) => !other.covers(int.parse(d.substring(0, 4)));
    return HolidayCalendar(
      years: {...years, ...other.years},
      off: {...off.where(keep), ...other.off},
      work: {...work.where(keep), ...other.work},
    );
  }
}

final _date = RegExp(r'^\d{4}-\d{2}-\d{2}$');

String _ymd(DateTime d) =>
    '${d.year.toString().padLeft(4, '0')}-'
    '${d.month.toString().padLeft(2, '0')}-'
    '${d.day.toString().padLeft(2, '0')}';

/// What a rider reads when a 平日／假日 judgment fell back on the weekend.
const holidayFallbackNote = '未取得國定假日資料，平日／假日依星期判斷';

/// Whether a period's or a slot's [days] (`all`, `weekday`, `holiday` or a
/// list of weekdays) hold on [day]. 平日 and 假日 follow the calendar; a
/// named weekday is that weekday, holiday or not.
bool daysHoldOn(Object? days, CalendarDay day) => switch (days) {
  'all' => true,
  'weekday' => !day.off,
  'holiday' => day.off,
  final List<Object?> list => list.contains(scheduleWeekdays[day.weekday]),
  _ => false,
};

/// Whether [days] depend on the calendar (平日 or 假日).
bool daysUseCalendar(Object? days) => days == 'weekday' || days == 'holiday';

/// The date and minute of [now] in Taiwan: the date as UTC midnight, and
/// the minutes since 00:00.
(DateTime, int) taipeiDateMinute(DateTime now) {
  final t = now.toUtc().add(const Duration(hours: 8));
  return (DateTime.utc(t.year, t.month, t.day), t.hour * 60 + t.minute);
}

int? _clock(String? hhmm) {
  if (hhmm == null || !RegExp(r'^([01]\d|2[0-3]):[0-5]\d$').hasMatch(hhmm)) {
    return null;
  }
  return int.parse(hhmm.substring(0, 2)) * 60 + int.parse(hhmm.substring(3));
}

/// The `[start, end)` minutes, counted from 00:00 of [date], that a period
/// on [days] from [from] to [to] covers on the days [first]..[last] after
/// [date] (negative is before). Decision 47: a period across midnight
/// belongs to the day it starts, so whether that day is 平日 or 假日 decides,
/// as [calendar] says. Without times it covers its days whole; with invalid
/// times (an editor's draft) nothing.
List<(int, int)> datedSpans(
  Object? days,
  String? from,
  String? to,
  DateTime date,
  HolidayCalendar calendar, {
  int first = -1,
  int last = 1,
}) {
  if (days == null) return const [];
  final allDay = from == null && to == null;
  final start = _clock(from), end = _clock(to);
  if (!allDay && (start == null || end == null || start == end)) {
    return const [];
  }
  return [
    for (var i = first; i <= last; i++)
      if (daysHoldOn(
        days,
        calendar.dayOf(DateTime.utc(date.year, date.month, date.day + i)),
      ))
        if (allDay)
          (i * 1440, i * 1440 + 1440)
        else if (start! < end!)
          (i * 1440 + start, i * 1440 + end)
        else
          (i * 1440 + start, i * 1440 + 1440 + end),
  ];
}

/// Whether any of [days] needed the calendar on a day it lacks, among the
/// days [first]..[last] after [date]: the judgment then fell back on the
/// weekend ([holidayFallbackNote]).
bool calendarFellBack(
  Iterable<Object?> days,
  DateTime date,
  HolidayCalendar calendar, {
  int first = -1,
  int last = 1,
}) {
  if (!days.any(daysUseCalendar)) return false;
  for (var i = first; i <= last; i++) {
    if (!calendar.covers(
      DateTime.utc(date.year, date.month, date.day + i).year,
    )) {
      return true;
    }
  }
  return false;
}
